#!/usr/bin/env python3
"""Retrieve and verify native CCMC volumes for the common solar-wind movie.

Original research inputs are read-only. Downloaded volumes and compact flux
arrays belong to this application; only the verification receipt is published.
"""
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
import argparse
import hashlib
import json
import time
import urllib.request

import numpy as np
import pandas as pd
from scipy.io import netcdf_file
from scipy.interpolate import RegularGridInterpolator

APP=Path(__file__).resolve().parents[1]
SOURCE=APP.parent/'mhd_llm'
ARCHIVE=SOURCE/'claude/ref/ccmc'
OUTPUT=APP/'runtime/ccmc'
RECEIPT=APP/'public/data/ccmc-movie-provenance.json'
RUN='Jan_Deca_120925_SH_1'
AU=1.495978707e11
MP=1.67239e-27  # The native ENLIL export's proton-mass convention.
START,END=61006.25,61014.0


def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()


def prepare(index,cache,listing):
    name=f'tim.{index:04d}.nc';row=listing[name]
    original=ARCHIVE/'raw/tim'/name
    path=original if original.exists() else cache/name
    if not path.exists() or path.stat().st_size!=int(row['size']):
        partial=path.with_suffix('.part')
        for attempt in range(12):
            try:
                # A distinct query avoids reusing intermittent upstream proxy
                # failures; the canonical archive URL is retained in receipts.
                request=urllib.request.Request(row['link']+f'&movie_fetch={attempt}',headers={'User-Agent':'Mozilla/5.0'})
                with urllib.request.urlopen(request,timeout=120) as response,partial.open('wb') as target:
                    while block:=response.read(1024*1024):target.write(block)
                if partial.stat().st_size!=int(row['size']):raise ValueError('Incomplete native volume')
                partial.replace(path);break
            except Exception as error:
                partial.unlink(missing_ok=True)
                if attempt==11:raise
                print(f'{name}: retry {attempt+1}: {error}',flush=True);time.sleep(min(2**attempt,16))
    raw_sha=sha(path)
    product=OUTPUT/f'flux-{index:04d}.npz'
    with netcdf_file(path,'r',mmap=False) as nc:
        assert nc.project.decode()==RUN and nc.coordinates.decode()=='HEEQ+180'
        assert nc.dimensions=={'n1':576,'n2':24,'n3':90,'nblk':2}
        v=nc.variables
        density=v['D'].data[0].astype(np.float64)/MP/1e6/(1+4*float(nc.xalpha))
        speed=np.sqrt(sum(v[key].data[0].astype(np.float64)**2 for key in ['V1','V2','V3']))
        flux=(density*speed*100).astype(np.float32) # cm^-3 * m/s -> cm^-2/s
        epoch=60949+float(v['TIME'].data)/86400
        radial=v['X1'].data[0].astype(np.float64)/AU
        theta=v['X2'].data[0].astype(np.float64)
        phi=v['X3'].data[0].astype(np.float64)
        np.savez_compressed(product,flux=flux,r_au=radial,theta=theta,phi=phi,timeMjd=epoch)
        # Native virtual probes are generated by interpolating primitive fields.
        # Check those fields directly, independently of the scalar movie flux.
        checks=[]
        for body in ['earth','stereoa','3I-Atlas']:
            with netcdf_file(ARCHIVE/f'raw/nc/evo.{body}.nc','r',mmap=False) as evolution:
                ev=evolution.variables;t=evolution.variables['TIME'].data.astype(float)
                j=int(np.argmin(abs(t-float(v['TIME'].data))))
                point=[float(ev['X3'].data[j]),float(ev['X2'].data[j]),float(ev['X1'].data[j])/AU]
                for key in ['D','V1','V2','V3']:
                    values=v[key].data[0].astype(float)
                    extended=np.r_[phi[-1]-2*np.pi,phi,phi[0]+2*np.pi]
                    values=np.concatenate([values[-1:],values,values[:1]],axis=0)
                    actual=float(RegularGridInterpolator((extended,theta,radial),values)([point])[0])
                    expected=float(ev[key].data[j,0])
                    checks.append({'body':body,'field':key,'absoluteError':abs(actual-expected),'reference':expected})
    print(f'{name}: {epoch:.8f} MJD; native volume verified and compacted',flush=True)
    return {'index':index,'timeMjd':epoch,'sourceUrl':row['link'],'sourceBytes':path.stat().st_size,
            'sourceSha256':raw_sha,'originalResearchPath':str(original.relative_to(SOURCE)) if original.exists() else None,
            'productPath':str(product.relative_to(APP)),'productBytes':product.stat().st_size,'productSha256':sha(product),
            'primitiveChecks':checks}


def earth_track():
    earth=pd.read_csv(SOURCE/'argon/data/raw/ephemeris/earth.csv')
    return earth.JD_UT.to_numpy()-2400000.5,earth[['x_au','y_au','z_au']].to_numpy()


def coordinate_matrix():
    return np.array(json.loads((SOURCE/'codex/observations/coordinate_system.json').read_text())['ecliptic_to_solar_equatorial_matrix'])


def archive_coordinates(xyz,epoch):
    rotation=coordinate_matrix();tt,earth=earth_track()
    earth=np.array([np.interp(epoch,tt,earth[:,j]) for j in range(3)])@rotation.T
    solar=np.asarray(xyz)@rotation.T
    radius=np.linalg.norm(solar,axis=-1)
    theta=np.arccos(np.divide(solar[...,2],radius,out=np.zeros_like(radius),where=radius>0))
    phi=(np.arctan2(solar[...,1],solar[...,0])-np.arctan2(earth[1],earth[0])+np.pi)%(2*np.pi)
    return phi,theta,radius


def coordinate_checks(snapshots):
    """Compare the display basis with independently archived body coordinates."""
    checks={}
    for body,name in [('earth','earth'),('stereoa','stereo_a'),('3I-Atlas','comet')]:
        if body=='earth':tt,xyz=earth_track()
        else:
            frame=pd.read_csv(SOURCE/f'codex/observations/ephemeris_{name}.tsv',sep='\t')
            tt=frame.mjd_utc.to_numpy();xyz=frame[['x_au','y_au','z_au']].to_numpy()
        errors=[]
        with netcdf_file(ARCHIVE/f'raw/nc/evo.{body}.nc','r',mmap=False) as nc:
            v=nc.variables;clock=v['TIME'].data.astype(float)/86400+60949
            azimuth=np.unwrap(v['X3'].data.astype(float))
            for row in snapshots:
                epoch=row['timeMjd'];point=np.array([np.interp(epoch,tt,xyz[:,j]) for j in range(3)])
                phi,theta,radius=archive_coordinates(point,epoch)
                delta=(phi-np.interp(epoch,clock,azimuth)+np.pi)%(2*np.pi)-np.pi
                errors.append([abs(np.degrees(delta)),abs(np.degrees(theta-np.interp(epoch,clock,v['X2'].data))),abs(radius/(np.interp(epoch,clock,v['X1'].data)/AU)-1)])
        longitude,latitude,radius=np.max(errors,axis=0)
        assert longitude<.2 and latitude<.1 and radius<.006,(body,longitude,latitude,radius)
        checks[body]={'maxLongitudeDifferenceDegrees':float(longitude),'maxLatitudeDifferenceDegrees':float(latitude),'maxRelativeRadiusDifference':float(radius)}
    return checks


def load_native(xx,yy):
    receipt=json.loads(RECEIPT.read_text());rows=receipt['snapshots']
    samples=[];times=[];xyz=np.stack([xx,yy,np.zeros_like(xx)],axis=-1)
    for row in rows:
        path=APP/row['productPath']
        assert sha(path)==row['productSha256'],'CCMC compact input changed'
        with np.load(path) as native:
            support=[float(native['r_au'][0]),float(native['r_au'][-1])]
            epoch=float(native['timeMjd']);phi,theta,r=archive_coordinates(xyz,epoch)
            pp=native['phi'];extended=np.r_[pp[-1]-2*np.pi,pp,pp[0]+2*np.pi]
            field=native['flux'];field=np.concatenate([field[-1:],field,field[:1]],axis=0)
            points=np.column_stack([phi.ravel(),theta.ravel(),r.ravel()])
            samples.append(RegularGridInterpolator((extended,native['theta'],native['r_au']),field,bounds_error=False,fill_value=np.nan)(points).reshape(xx.shape).astype(np.float32))
            times.append(epoch)
    times=np.asarray(times)
    assert times[0]<=START<END<=times[-1] and np.all(np.diff(times)>0)
    selected=np.arange(max(0,np.searchsorted(times,START,side='right')-1),min(len(times),np.searchsorted(times,END)+1))
    meta={'name':'CCMC WSA–ENLIL','reference':RUN,'solverDimensions':[576,24,90],
          'nativeSliceDimensions':[576,90],'nativeSliceAxes':['radius','longitude'],
          'nativePlane':'J2000 ecliptic z = 0, sampled from native 3-D HEEQ+180 volumes',
          'definition':'nₚ |v|','nominalCadenceHours':6,
          'qualification':'External CCMC benchmark with the archived 64-cone input catalogue. Native 3-D output is approximately six-hourly; intermediate display epochs interpolate physical flux.',
          'nativeTimeMjd':times.tolist(),'usedNativeTimeMjd':times[selected].tolist(),
          'actualCadenceHours':{'minimum':float(np.min(np.diff(times))*24),'median':float(np.median(np.diff(times))*24),'maximum':float(np.max(np.diff(times))*24)},
          'sourceReceiptUrl':'/data/ccmc-movie-provenance.json','sourceReceiptSha256':sha(RECEIPT),
          'supportRadiusAu':support}
    return times[selected],[samples[i] for i in selected],np.hypot(xx,yy).astype(np.float32),meta


def make_receipt(snapshots):
    return {'schemaVersion':1,'runId':RUN,'runUrl':f'https://ccmc.gsfc.nasa.gov/ror/results/viewrun.php?runnumber={RUN}',
             'block':0,'blockMeaning':'CME run; ambient control block is excluded from this movie.',
             'grid':[576,24,90],'nativeCoordinates':'HEEQ+180','displayCoordinates':'J2000 ecliptic x/y, z = 0',
             'coordinateTransform':'Fixed J2000 solar-pole rotation; subtract Earth solar-equatorial azimuth at each native epoch, then add pi for HEEQ+180.',
             'densityConvention':'np = D / mp / (1 + 4*xalpha), xalpha=0.05; applied once. mp=1.67239e-27 kg matches the native export.',
             'fluxConvention':'np * sqrt(V1^2+V2^2+V3^2); SI velocity converted to cm/s.',
             'coordinateChecks':coordinate_checks(snapshots),
             'coordinateQualification':'The fixed-J2000 display ephemerides and the archived virtual-probe ephemerides differ slightly. Recorded differences are below 0.2 degree longitude and 0.1 degree latitude, compared with the native 4-degree angular cells.',
             'sourceInputs':[{'path':name,'sha256':sha(SOURCE/name)} for name in ['codex/observations/coordinate_system.json','argon/data/raw/ephemeris/earth.csv','codex/observations/ephemeris_stereo_a.tsv','codex/observations/ephemeris_comet.tsv']],
             'snapshots':snapshots,'builder':'scripts/prepare_ccmc_movie.py','builderSha256':sha(__file__)}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache',type=Path,default=APP/'runtime/ccmc/raw')
    parser.add_argument('--workers',type=int,default=3)
    args=parser.parse_args();args.cache.mkdir(parents=True,exist_ok=True);OUTPUT.mkdir(parents=True,exist_ok=True)
    listing={row['file']:row for row in json.loads((ARCHIVE/'raw/run_files.json').read_text())['files']}
    snapshots=[];failures=[]
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures={pool.submit(prepare,index,args.cache,listing):index for index in range(228,261)}
        for future in as_completed(futures):
            try:snapshots.append(future.result())
            except Exception as error:failures.append(futures[future]);print(f'Native snapshot {futures[future]} unavailable: {error}',flush=True)
    if failures:raise RuntimeError(f'Missing native snapshots: {failures}; rerun to resume from the cache.')
    snapshots.sort(key=lambda row:row['index'])
    receipt=make_receipt(snapshots)
    RECEIPT.write_text(json.dumps(receipt,ensure_ascii=False,indent=2)+'\n')
    print('Prepared',len(snapshots),'native CCMC volumes; original research files were not changed.',flush=True)


if __name__=='__main__':main()
